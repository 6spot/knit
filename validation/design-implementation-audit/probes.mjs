import { mkdtempSync, mkdirSync, writeFileSync, readFileSync, rmSync, chmodSync, statSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join, resolve, dirname, basename } from 'node:path';
import { execFileSync } from 'node:child_process';
import { pathToFileURL } from 'node:url';
const root = resolve(process.argv[2]);
const load = (path) => import(pathToFileURL(join(root, 'dist', path)));
const { InitializationService } = await load('application/initialization.js');
const { SqliteMetadataStore } = await load('infrastructure/sqlite-metadata-store.js');
const { TaskService } = await load('application/task-service.js');
const { ContextPlanner } = await load('application/context-planner.js');
const { StatusService } = await load('application/status-service.js');
const { currentEntry, scopeDigest } = await load('application/scope.js');
const { parseTaskDocument } = await load('application/task-document.js');
const { onInputsUpdated } = await load('domain/task.js');
const results = [];
const dir = mkdtempSync(join(tmpdir(), 'knit-audit-probe-'));
const git = (...args) => execFileSync('git', args, { cwd: dir, encoding: 'utf8' }).trim();
let store;
const oldUmask = process.umask(0o022);
try {
  git('init', '-b', 'main'); git('config', 'user.name', 'Audit'); git('config', 'user.email', 'audit@example.test');
  mkdirSync(join(dir, '.knit', '.runtime'), { recursive: true, mode: 0o755 });
  chmodSync(join(dir, '.knit', '.runtime'), 0o755);
  await new InitializationService().execute({ dir, client: 'pi' });
  writeFileSync(join(dir, 'run.sh'), '#!/bin/sh\nexit 0\n', { mode: 0o644 });
  git('add', '-A'); git('commit', '-qm', 'fixture');
  store = new SqliteMetadataStore(join(dir, '.knit', '.runtime', 'metadata.db'));
  const tasks = new TaskService({ store });
  const task = await tasks.newTask({ dir, title: 'Audit fixture', slug: 'audit-fixture' });
  await tasks.record({ dir, taskId: task.taskId, body: '隔离审计夹具' });
  await tasks.ready({ dir, taskId: task.taskId });
  const planner = new ContextPlanner({ store });
  const before = await planner.plan({ dir, taskId: task.taskId, role: 'check' });
  const rolePath = join(dir, '.knit', 'agents', 'check.md');
  writeFileSync(rolePath, readFileSync(rolePath, 'utf8') + '\n审计：新增检查要求。\n');
  const after = await planner.plan({ dir, taskId: task.taskId, role: 'check' });
  results.push({ case: 'role-instructions-digest', roleDigestChanged: before.sections.find(x => x.kind === 'role').digest !== after.sections.find(x => x.kind === 'role').digest, effectiveDigestChanged: before.effectiveInputsDigest !== after.effectiveInputsDigest, standardsDigestChanged: before.standardsDigest !== after.standardsDigest });
  const first = currentEntry(dir, 'run.sh');
  chmodSync(join(dir, 'run.sh'), 0o755);
  const last = currentEntry(dir, 'run.sh');
  results.push({ case: 'scope-mode-change', fingerprintChanged: scopeDigest([first]) !== scopeDigest([last]), mode: (statSync(join(dir, 'run.sh')).mode & 0o777).toString(8) });
  results.push({ case: 'preexisting-runtime-permissions', runtimeMode: (statSync(join(dir, '.knit', '.runtime')).mode & 0o777).toString(8), databaseMode: (statSync(join(dir, '.knit', '.runtime', 'metadata.db')).mode & 0o777).toString(8), walMode: (statSync(join(dir, '.knit', '.runtime', 'metadata.db-wal')).mode & 0o777).toString(8) });
  const saved = await tasks.update({dir,taskId:task.taskId,kind:'change',reason:'audit pending change',content:'## 目标与边界\n\nchanged goal\n',runActive:true});
  const applied = await tasks.update({dir,taskId:task.taskId,expectPending:saved.pendingDraftDigest});
  const reread = parseTaskDocument(readFileSync(join(dir,'.knit',task.relativePath),'utf8'));
  results.push({case:'pending-phase-persistence',responsePhase:applied.phase,diskPhase:reread.frontmatter.phase,pendingCleared:(await store.bindings.get(task.taskId)).pendingDraft===null});
  results.push({case:'completed-input-update-domain',decision:onInputsUpdated({status:'closed',outcome:'completed',phase:'deliver'},'change',true)});
  await tasks.close({ dir, taskId: task.taskId, outcome: 'cancelled', runsSettled: true });
  const archived = join(dir, '.knit', 'tasks', 'archive', '2026-11', basename(dirname(task.relativePath)));
  mkdirSync(join(dir, '.knit', 'tasks', 'archive', '2026-11'), { recursive: true });
  const { renameSync } = await import('node:fs');
  renameSync(join(dir, '.knit', dirname(task.relativePath)), archived);
  const taskList = tasks.list({ dir });
  const status = new StatusService({ store });
  const statusList = await status.status({ dir });
  let taskStatus;
  try { taskStatus = (await status.status({ dir, taskId: task.taskId })).taskId; }
  catch (error) { taskStatus = error.message; }
  results.push({ case: 'archived-task-status', taskId: task.taskId, listedByTasks: taskList.archived.some(x => x.taskId === task.taskId), listedByStatus: statusList.tasks.some(x => x.taskId === task.taskId), taskStatus });
  console.log(JSON.stringify(results, null, 2));
} finally { store?.close(); process.umask(oldUmask); rmSync(dir, { recursive: true, force: true }); }
